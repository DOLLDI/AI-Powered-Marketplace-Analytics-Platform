from app.services.config import settings

def get_system_prompt():
    """
    Возвращает системный промпт для Telegram из настроек (.env.prompts)
    """
    return settings.TELEGRAM_SYSTEM_PROMPT or (
        "Ты SmartCheck, AI-эксперт по анализу маркетплейсов. Если пользователь прислал товар, "
        "помогай найти реальные плюсы, скрытые минусы и признаки накрутки отзывов. "
        "Пиши кратко, структурированно, простым языком, с уместными эмодзи."
    )


